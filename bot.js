// Каждую неделю, понедельник, среда, пятница в 14:00
cron.schedule('0 14 * * 1,3,5', () => {
    bot.sendPoll(
        CHAT_ID,
        "Идёте ли вы сегодня в зал? 💪",
        ["Да", "Нет", "Может быть"],
        { is_anonymous: false }
    );
});

bot.on('poll_answer', (answer) => {
    const userId = answer.user.id;
    const username = answer.user.username || answer.user.first_name;

    // Найти или создать запись для пользователя
    if (!userStreaks[userId]) {
        userStreaks[userId] = { count: 0, username };
    }

    // Найти вариант, который выбрал пользователь
    const selectedOption = answer.option_ids[0]; // первый вариант (0 = Да)

    if (selectedOption === 0) { // 0 = "Да"
        userStreaks[userId].count += 1;
    } else { // Если выбрал "Нет" или "Может быть"
        userStreaks[userId].count = 0; // сброс счётчика
    }

    console.log(`${username} — ${userStreaks[userId].count} подряд`);

    // Проверяем достижение 3 подряд (или 10)
    if (userStreaks[userId].count === 3) {
        bot.sendMessage(
            CHAT_ID,
            `🎉 @${username} красавчик! 3 тренировки подряд! 💪`
        );
    }

    // --- Новый функционал: сообщение при "Нет" ---
    if (selectedOption === 1) { // 1 = "Нет"
        bot.sendMessage(
            CHAT_ID,
            `😢 @${username}, пидора ответ! 💪`
        );
    }
});

